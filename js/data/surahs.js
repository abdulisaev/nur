export const SURAHS = SURAH_META.map(([ar, ayahs, type], i) => ({
  n: i + 1,
  ar,
  name: NAMES[i][0],
  meaning: NAMES[i][1],
  ayahs,
  type,
  typeName: type === "m" ? "Мекканская" : "Мединская",
}));

export const surah = (n) => SURAHS[n - 1];

export const JUZ = JUZ_STARTS.map(([s, a], i) => ({ n: i + 1, s, a }));

export function juzOf(s, a) {
  let j = 1;
  for (const z of JUZ) {
    if (z.s < s || (z.s === s && z.a <= a)) j = z.n;
    else break;
  }
  return j;
}

