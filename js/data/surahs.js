import { SURAH_META, JUZ_STARTS, SAJDA, PAGE_STARTS } from "./quran-meta.js";

export const PAGE_COUNT = PAGE_STARTS.length;
const before = (s1, a1, s2, a2) => s1 < s2 || (s1 === s2 && a1 < a2);

// Номер страницы мусхафа, на которой находится аят
export function pageOf(s, a) {
  let lo = 0, hi = PAGE_STARTS.length - 1;
  while (lo < hi) {
    const mid = (lo + hi + 1) >> 1;
    const [ps, pa] = PAGE_STARTS[mid];
    if (before(s, a, ps, pa)) hi = mid - 1;
    else lo = mid;
  }
  return lo + 1;
}

// Аяты страницы: [{ s, from, to }] — страница может захватывать несколько сур
export function pageRanges(page) {
  const [s1, a1] = PAGE_STARTS[page - 1];
  const next = PAGE_STARTS[page];
  const [s2, a2] = next ? (next[1] > 1 ? [next[0], next[1] - 1] : [next[0] - 1, SURAH_META[next[0] - 2][1]]) : [114, 6];
  const ranges = [];
  for (let s = s1; s <= s2; s++) ranges.push({ s, from: s === s1 ? a1 : 1, to: s === s2 ? a2 : SURAH_META[s - 1][1] });
  return ranges;
}

